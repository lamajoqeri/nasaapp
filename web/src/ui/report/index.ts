// The report page: a research-paper write-up of the current scenarios. Toolbar, title block, then the sections in
// order. Each section fills in as soon as its own work is done. Owner: shell agent (layout, toolbar, print).
import './report.css';
import { coord, utc } from '../format';
import { chip, esc } from './dom';
import { abstractSection, confidenceSection, conclusionSection, resultsSection, sitesSection } from './results';
import { dataSection, introSection, limitsSection, methodsSection, referencesSection } from './text';
import { validationSection } from './validation';
import type { ReportCtx, ReportInput, SectionFn } from './types';

const ORDER: SectionFn[] = [
  abstractSection, introSection, dataSection, methodsSection, sitesSection, resultsSection,
  validationSection, confidenceSection, limitsSection, conclusionSection, referencesSection,
];

export async function mountReport(el: HTMLElement, input: ReportInput): Promise<{ destroy(): void }> {
  const ac = new AbortController();
  const ctx: ReportCtx = { ...input, signal: ac.signal };
  const names = [...new Set(input.scenarios.map((s) => s.name))];
  const title = names.length > 1 ? `${names.slice(0, -1).join(', ')} and ${names.at(-1)}` : names[0];
  const wrap = document.createElement('div');
  wrap.className = 'r-root';
  wrap.innerHTML = `
    <div class="r-bar"><div class="r-bar-in">
      <button type="button" class="r-back">← Back to mission</button>
      <button type="button" class="r-print" disabled>Print / save PDF</button>
    </div></div>
    <article class="report">
      <header class="r-title">
        <p class="r-kicker">Landing site report</p>
        <h1>Sunlight and Earth visibility at ${esc(title)}</h1>
        <p class="r-byline">Generated by Southern-Luna on ${utc(input.generatedAt)}</p>
        <ul class="r-scen">${input.scenarios.map((s) => `<li>${chip(s.letter, s.color)} <b>${esc(s.name)}</b>
          <span>${coord(s.sc.spec.lat, s.sc.spec.lon)}, landing ${utc(s.sc.spec.t)}</span></li>`).join('')}</ul>
        ${input.skipped.length ? `<p class="r-note">Not included: scenario ${input.skipped.map(esc).join(', ')}, which had no results yet.</p>` : ''}
        <p class="r-reopen">Reopen this exact analysis: <a href="${esc(input.link)}" target="_blank" rel="noopener">${esc(input.link)}</a></p>
        <nav class="r-toc" aria-label="Contents"></nav>
      </header>
    </article>`;
  const paper = wrap.querySelector<HTMLElement>('.report')!, toc = wrap.querySelector<HTMLElement>('.r-toc')!;
  const print = wrap.querySelector<HTMLButtonElement>('.r-print')!;
  wrap.querySelector<HTMLButtonElement>('.r-back')!.onclick = () => input.close();
  print.onclick = () => { // the title names the saved PDF
    const t = document.title;
    document.title = `Southern-Luna report, ${title}`;
    window.print();
    document.title = t;
  };
  // In-page links (contents, citations): scroll instead of changing the hash, which the app treats as a new link.
  wrap.addEventListener('click', (e) => {
    const href = (e.target as Element).closest('a')?.getAttribute('href');
    if (!href?.startsWith('#')) return;
    e.preventDefault();
    document.getElementById(decodeURIComponent(href.slice(1)))?.scrollIntoView({ behavior: 'smooth', block: 'start' });
  }, { signal: ac.signal });
  el.append(wrap);

  const fillToc = () => {
    toc.innerHTML = '<span>Contents</span>' + [...paper.querySelectorAll<HTMLElement>(':scope > .r-sec')]
      .map((s) => `<a href="#${s.id}">${esc(s.querySelector('h2')?.textContent ?? '')}</a>`).join('');
  };
  await Promise.all(ORDER.map(async (fn) => {
    const slot = document.createElement('div');
    slot.className = 'r-slot';
    slot.innerHTML = '<p class="r-status">Working…</p>';
    paper.append(slot);
    try { const sec = await fn(ctx); if (!ac.signal.aborted) { slot.replaceWith(sec); fillToc(); } }
    catch (e) { if (!ac.signal.aborted) slot.innerHTML = `<p class="r-status r-err" role="alert">This section failed: ${esc((e as Error).message)}</p>`; }
  }));
  print.disabled = false;
  return { destroy() { ac.abort(); wrap.remove(); } };
}
