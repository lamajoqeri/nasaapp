// The report page: a research-paper write-up of the current scenarios. Title block, then the sections in order.
// Each section fills in as soon as its own work is done. Owner: shell agent (layout, toolbar, print).
import './report.css';
import { esc } from './dom';
import { abstractSection, confidenceSection, conclusionSection, resultsSection, sitesSection } from './results';
import { dataSection, introSection, limitsSection, methodsSection, referencesSection } from './text';
import { validationSection } from './validation';
import type { ReportCtx, ReportInput, SectionFn } from './types';

const ORDER: SectionFn[] = [
  abstractSection, introSection, dataSection, methodsSection, sitesSection, resultsSection,
  validationSection, confidenceSection, limitsSection, conclusionSection, referencesSection,
];

export async function mountReport(el: HTMLElement, input: ReportInput): Promise<{ destroy(): void }> {
  const ac = new AbortController();
  const ctx: ReportCtx = { ...input, signal: ac.signal };
  const root = document.createElement('article');
  root.className = 'report';
  root.innerHTML = `
    <div class="r-bar"><button type="button" class="r-back">Back to mission</button><button type="button" class="r-print">Print / save PDF</button></div>
    <header class="r-title"><h1>Landing site assessment: ${input.scenarios.map((s) => esc(s.name)).join(', ')}</h1>
      <p class="r-byline">Generated by Southern-Luna, ${new Date(input.generatedAt).toISOString().slice(0, 16).replace('T', ' ')} UTC</p></header>`;
  root.querySelector<HTMLButtonElement>('.r-back')!.onclick = () => input.close();
  root.querySelector<HTMLButtonElement>('.r-print')!.onclick = () => window.print();
  el.append(root);
  await Promise.all(ORDER.map(async (fn) => {
    const slot = document.createElement('div');
    slot.className = 'r-slot';
    slot.innerHTML = '<p class="r-status">Working…</p>';
    root.append(slot);
    try { const sec = await fn(ctx); if (!ac.signal.aborted) slot.replaceWith(sec); }
    catch (e) { if (!ac.signal.aborted) slot.innerHTML = `<p class="r-status r-err" role="alert">This section failed: ${esc((e as Error).message)}</p>`; }
  }));
  return { destroy() { ac.abort(); root.remove(); } };
}
